import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { parse } from 'smol-toml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = path.join(root, '.private', 'moments');
const output = path.join(root, 'public', 'images', 'moments');
const config = parse(await fs.readFile(path.join(root, 'content', '主页文字.toml'), 'utf8'));
const sigma = Number(config.moments?.blur_sigma ?? 24);
if (!Number.isFinite(sigma) || sigma < 8 || sigma > 100) {
  throw new Error('blur_sigma 需为 8–100，默认 24。');
}

async function imagesIn(directory) {
  const files = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await imagesIn(file));
    else if (entry.isFile() && /\.(jpe?g|png|webp|avif|tiff?)$/i.test(entry.name)) files.push(file);
  }
  return files.sort((a, b) => a.localeCompare(b, 'zh-CN'));
}

await fs.mkdir(input, { recursive: true });
await fs.mkdir(output, { recursive: true });
const sources = await imagesIn(input);
if (!sources.length) {
  // A CI checkout has no private originals; keep its committed blurred photos.
  try { await fs.access(path.join(output, 'index.json')); }
  catch { await fs.writeFile(path.join(output, 'index.json'), '[]\n'); }
  console.log('时刻：没有待处理的本地原片，保留已生成的相册。');
  process.exit(0);
}
const manifest = [];
const seen = new Set();
for (const file of sources) {
  const bytes = await fs.readFile(file);
  const id = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const name = `${id}.webp`;
  if (seen.has(name)) continue;
  seen.add(name);
  // EXIF is read for orientation, then discarded. Only blurred pixels are exported.
  const result = await sharp(bytes, { failOn: 'error' }).rotate()
    .resize({ width: 1440, height: 1800, fit: 'inside', withoutEnlargement: true })
    .blur(sigma).webp({ quality: 84 }).toBuffer({ resolveWithObject: true });
  await fs.writeFile(path.join(output, name), result.data);
  manifest.push({ src: `/images/moments/${name}`, width: result.info.width, height: result.info.height });
}

await fs.writeFile(path.join(output, 'index.json'), `${JSON.stringify(manifest, null, 2)}\n`);
// Synchronize only files generated by this script; original files are never changed.
for (const name of await fs.readdir(output)) {
  if (/^[a-f0-9]{16}\.webp$/.test(name) && !seen.has(name)) await fs.unlink(path.join(output, name));
}
console.log(`时刻：已生成 ${manifest.length} 张高斯模糊照片（强度 ${sigma}），原片保留在 .private/moments。`);
